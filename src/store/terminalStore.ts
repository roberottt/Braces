import { createStore } from "solid-js/store";
import type { Lang } from "../i18n";

export type Provider = "ollama" | "anthropic" | "openai" | "lmstudio" | "xai" | "gemini" | "nvidia" | "mock";

export type ToolPanelId = "ai" | "git" | "review";

export type Tab = {
  id: string;
  title: string;
  cwd: string;
  lastExitCode: number | null;
};

export type EditorTab = {
  id: string;
  relPath: string;
  title: string;
  dirty: boolean;
};

export type TerminalStore = {
  cwd: string;
  lastExitCode: number | null;
  provider: Provider;
  model: string;
  /** True once tabs have been loaded from the DB (or confirmed empty). */
  hydrated: boolean;
  /** Whether terminal sessions and block history persist across app restarts. */
  persistSessions: boolean;
  /**
   * Whether inline command suggestions are generated by the AI provider using
   * what the user is doing (cwd, git branch, recent commands). When off, the
   * input bar falls back to plain prefix matching over local command history.
   */
  aiSuggestions: boolean;
  sidePanelOpen: boolean;
  /** Custom width (px) per tool panel, set by dragging its left edge; null = default CSS width. */
  panelWidth: Record<ToolPanelId, number | null>;
  /** Tool panel currently maximized over the whole workspace, if any. */
  panelMaximized: ToolPanelId | null;
  metricsOpen: boolean;
  theme: string;
  // Error intelligence
  errorPanelOpen: boolean;
  errorAnalysis: string;
  errorFix: string;
  // Semantic history search
  historySearchOpen: boolean;
  historyResults: string[];
  // Settings panel
  settingsOpen: boolean;
  language: Lang;
  // Tab management
  tabs: Tab[];
  activeTabId: string;
  tabsSidebarOpen: boolean;
  // Git integration
  gitPanelOpen: boolean;
  codeReviewOpen: boolean;
  workspaceOpen: boolean;
  leftDockView: "sessions" | "files";
  gitIsRepo: boolean;
  gitBranch: string;
  gitAhead: number;
  gitBehind: number;
  gitChangedCount: number;
  gitInsertions: number;
  gitDeletions: number;
  gitSelectedFile: string | null;
  gitSelectedStaged: boolean;
  // Prompt queued for the AI side panel (e.g. "explain this block"); the panel
  // consumes and clears it on mount / when it changes.
  pendingAiPrompt: string | null;
  // Editor view
  currentView: "terminal" | "editor";
  editorTabs: EditorTab[];
  activeEditorTabId: string | null;
};

let _tabCounter = 0;
export const genTabId = () => `tab-${Date.now()}-${_tabCounter++}`;

let _editorTabCounter = 0;
export const genEditorTabId = () => `edit-${Date.now()}-${_editorTabCounter++}`;

const initialTabId = genTabId();

export const [store, setStore] = createStore<TerminalStore>({
  cwd: "~",
  lastExitCode: null,
  provider: "ollama",
  model: "llama3.2",
  hydrated: false,
  persistSessions: (localStorage.getItem("braces_persist_sessions") ?? "true") !== "false",
  // Opt-in: off unless the user turned it on (first-run wizard or Settings → AI).
  aiSuggestions: localStorage.getItem("braces_ai_suggestions") === "true",
  sidePanelOpen: false,
  panelWidth: { ai: null, git: null, review: null },
  panelMaximized: null,
  metricsOpen: false,
  theme: "neon-noir",
  errorPanelOpen: false,
  errorAnalysis: "",
  errorFix: "",
  historySearchOpen: false,
  historyResults: [],
  settingsOpen: false,
  language: (localStorage.getItem("braces_language") as Lang | null) ?? "es",
  tabs: [{ id: initialTabId, title: (localStorage.getItem("braces_language") === "en" ? "New session" : "Nueva sesión"), cwd: "~", lastExitCode: null }],
  activeTabId: initialTabId,
  tabsSidebarOpen: true,
  // Git integration
  gitPanelOpen: false,
  codeReviewOpen: false,
  workspaceOpen: false,
  leftDockView: "sessions",
  gitIsRepo: false,
  gitBranch: "",
  gitAhead: 0,
  gitBehind: 0,
  gitChangedCount: 0,
  gitInsertions: 0,
  gitDeletions: 0,
  gitSelectedFile: null,
  gitSelectedStaged: false,
  pendingAiPrompt: null,
  // Editor view
  currentView: "terminal",
  editorTabs: [],
  activeEditorTabId: null,
});
